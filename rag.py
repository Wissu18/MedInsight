class MedicalRAGSystem:
    def __init__(self, df, chroma_client=None, collection=None):
        self.df = df
        self.chroma_client = chroma_client
        self.collection = collection

        # Initialiser le modèle d'embedding
        from sentence_transformers import SentenceTransformer
        self.model = SentenceTransformer('all-MiniLM-L6-v2')
        print("✅ Modèle d'embedding initialisé")

        print("✅ Système RAG initialisé")

    def search_similar(self, query, k=5):
        """Rechercher des documents similaires"""
        if self.collection:
            try:
                # Générer l'embedding pour la requête
                query_embedding = self.model.encode([query]).tolist()[0]

                # Rechercher dans la collection
                results = self.collection.query(
                    query_embeddings=[query_embedding],
                    n_results=k,
                    include=["documents", "metadatas", "distances"]
                )

                # Convertir au format Document
                from langchain_core.documents import Document

                docs = []
                if results['documents']:
                    for i in range(len(results['documents'][0])):
                        doc = Document(
                            page_content=results['documents'][0][i],
                            metadata=results['metadatas'][0][i]
                        )
                        docs.append(doc)

                return docs
            except Exception as e:
                print(f"⚠️ Erreur recherche ChromaDB: {e}")
                pass

        # Fallback: recherche simple
        return self._fallback_search(query, k)

    def _fallback_search(self, query, k=5):
        """Recherche fallback par mots-clés"""
        from langchain_core.documents import Document
        from collections import Counter

        query_lower = query.lower()
        results = []

        # Recherche dans les patients
        for idx, row in self.df.iterrows():
            score = 0

            # Vérifier les correspondances
            for col in ['Diagnosis', 'Symptom_1', 'Symptom_2', 'Symptom_3', 'Treatment_Plan']:
                if col in row:
                    if any(word in str(row[col]).lower() for word in query_lower.split()):
                        score += 1

            if score > 0:
                patient_text = f"""
                Patient ID: {row.get('Patient_ID', idx)}
                Age: {row.get('Age', 'N/A')}
                Gender: {row.get('Gender', 'N/A')}
                Diagnosis: {row.get('Diagnosis', 'N/A')}
                Symptoms: {row.get('Symptom_1', 'N/A')}, {row.get('Symptom_2', 'N/A')}, {row.get('Symptom_3', 'N/A')}
                Treatment: {row.get('Treatment_Plan', 'N/A')}
                """

                results.append((
                    score,
                    Document(
                        page_content=patient_text,
                        metadata={
                            "doc_type": "patient_record",
                            "patient_id": row.get('Patient_ID', idx),
                            "diagnosis": row.get('Diagnosis', 'N/A'),
                            "source": "keyword_fallback"
                        }
                    )
                ))

        # Trier par score
        results.sort(key=lambda x: x[0], reverse=True)
        return [doc for _, doc in results[:k]]

    def analyze_query_type(self, question):
        """Analyser le type de question"""
        question_lower = question.lower()

        query_types = {
            "patient_info": ["patient", "id", "âge", "age", "genre", "gender", "dossier"],
            "diagnosis": ["diagnostic", "diagnosis", "maladie", "condition", "pathologie"],
            "symptoms": ["symptôme", "symptom", "souffre", "présente", "a"],
            "vitals": ["tension", "pression", "cardiaque", "température", "saturation", "bpm", "mmhg", "°c", "%"],
            "treatment": ["traitement", "treatment", "médicament", "thérapie", "plan"],
            "statistics": ["combien", "nombre", "statistique", "moyenne", "pourcentage", "fréquence", "répartition"],
            "severity": ["sévérité", "severity", "grave", "critique", "modéré", "léger"],
            "correlation": ["relation", "corrélation", "lié", "associé", "en fonction"]
        }

        detected_types = []
        for q_type, keywords in query_types.items():
            if any(keyword in question_lower for keyword in keywords):
                detected_types.append(q_type)

        return detected_types if detected_types else ["general"]

    def get_data_insights(self, query_type):
        """Obtenir des insights basés sur le type de question"""
        insights = ""

        if "statistics" in query_type:
            insights += f"\n📊 **STATISTIQUES GÉNÉRALES:**\n"
            insights += f"• Nombre total de patients: {len(self.df)}\n"
            insights += f"• Âge moyen: {self.df['Age'].mean():.1f} ans\n"

            if 'Gender' in self.df.columns:
                gender_counts = self.df['Gender'].value_counts()
                for gender, count in gender_counts.items():
                    percentage = count / len(self.df) * 100
                    insights += f"• {gender}: {count} patients ({percentage:.1f}%)\n"

        if "diagnosis" in query_type and 'Diagnosis' in self.df.columns:
            insights += f"\n🏥 **DIAGNOSTICS PRÉSENTS:**\n"
            top_diagnoses = self.df['Diagnosis'].value_counts().head(5)
            for diag, count in top_diagnoses.items():
                percentage = count / len(self.df) * 100
                insights += f"• {diag}: {count} patients ({percentage:.1f}%)\n"

        if "vitals" in query_type:
            insights += f"\n❤️ **SIGNE VITAUX MOYENS:**\n"
            if 'Heart_Rate_bpm' in self.df.columns:
                insights += f"• Fréquence cardiaque moyenne: {self.df['Heart_Rate_bpm'].mean():.1f} bpm\n"
            if 'Body_Temperature_C' in self.df.columns:
                insights += f"• Température moyenne: {self.df['Body_Temperature_C'].mean():.1f}°C\n"
            if 'Oxygen_Saturation_%' in self.df.columns:
                insights += f"• Saturation O2 moyenne: {self.df['Oxygen_Saturation_%'].mean():.1f}%\n"

        return insights

    def query_dataframe(self, question):
        """Interroger directement le DataFrame pour des réponses précises"""
        question_lower = question.lower()

        # Recherche par ID patient
        if "patient" in question_lower and any(char.isdigit() for char in question):
            import re
            numbers = re.findall(r'\d+', question)
            if numbers:
                patient_id = int(numbers[0])
                if 'Patient_ID' in self.df.columns:
                    patient_data = self.df[self.df['Patient_ID'] == patient_id]
                    if not patient_data.empty:
                        return patient_data.iloc[0].to_dict()

        # Questions statistiques
        if "combien" in question_lower:
            if "patient" in question_lower or "nombre" in question_lower:
                return {"total_patients": len(self.df)}

            if "diagnostic" in question_lower and 'Diagnosis' in self.df.columns:
                if "flu" in question_lower or "grippe" in question_lower:
                    count = len(self.df[self.df['Diagnosis'].str.contains('Flu', case=False, na=False)])
                    return {"flu_patients": count}
                elif "covid" in question_lower:
                    count = len(self.df[self.df['Diagnosis'].str.contains('COVID', case=False, na=False)])
                    return {"covid_patients": count}

        # Moyennes
        if "moyenne" in question_lower or "moyen" in question_lower:
            if "âge" in question_lower or "age" in question_lower:
                return {"average_age": self.df['Age'].mean()}

            if "tension" in question_lower or "pression" in question_lower:
                if 'Systolic_mmHg' in self.df.columns:
                    return {
                        "avg_systolic": self.df['Systolic_mmHg'].mean(),
                        "avg_diastolic": self.df['Diastolic_mmHg'].mean()
                    }

        return None

    def generate_response(self, question, context_docs, query_types, direct_answer=None):
        """Générer une réponse basée sur le contexte"""

        # Préparer le contexte
        context = ""
        for i, doc in enumerate(context_docs[:3]):
            context += f"\n--- Document {i+1} ---\n"
            # Limiter la longueur du contexte
            context += doc.page_content[:300] + "...\n"

        # Insights supplémentaires
        insights = self.get_data_insights(query_types)

        # Construction de la réponse
        response = f"""🤖 **RÉPONSE À VOTRE QUESTION:**\n\n"""
        response += f"**Question:** {question}\n\n"

        if direct_answer:
            response += f"**Données directes:**\n"
            for key, value in direct_answer.items():
                response += f"• {key}: {value}\n"
            response += f"\n"

        if context:
            response += f"**Contexte trouvé:**\n{context}\n"

        if insights:
            response += f"**Insights statistiques:**\n{insights}\n"

        # Ajouter des recommandations basées sur le type de question
        if "diagnosis" in query_types:
            response += f"\n💡 **Recommandation:** Pour des informations détaillées sur un diagnostic spécifique, précisez le nom de la maladie."

        if "patient" in query_types:
            response += f"\n💡 **Recommandation:** Pour consulter un dossier patient complet, fournissez l'ID du patient."

        response += f"\n---\n"
        response += f"*Source: Base de données médicale de {len(self.df)} patients*"

        return response

    def answer_question(self, question):
        """Répondre à une question"""
        print(f"\n🔍 Analyse de la question: '{question}'")

        # 1. Analyser le type de question
        query_types = self.analyze_query_type(question)
        print(f"   Types détectés: {query_types}")

        # 2. Rechercher dans la base vectorielle
        print("   Recherche dans la base de connaissances...")
        similar_docs = self.search_similar(question, k=5)
        print(f"   Documents pertinents trouvés: {len(similar_docs)}")

        # 3. Interroger le DataFrame directement si pertinent
        direct_answer = self.query_dataframe(question)
        if direct_answer:
            print("   Données directes extraites du dataset")

        # 4. Générer la réponse
        print("   Génération de la réponse...")
        response = self.generate_response(
            question=question,
            context_docs=similar_docs,
            query_types=query_types,
            direct_answer=direct_answer
        )

        # 5. Préparer les sources
        sources = []
        for doc in similar_docs[:3]:
            source_info = {
                "content_preview": doc.page_content[:100] + "...",
                "metadata": doc.metadata,
                "type": doc.metadata.get('doc_type', 'unknown')
            }
            sources.append(source_info)

        return {
            "answer": response,
            "sources": sources,
            "query_types": query_types,
            "direct_data": direct_answer is not None
        }

